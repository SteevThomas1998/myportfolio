// Generates src/lib/travel-map-dots.ts: a dot-matrix of land for the travel
// page map, with each dot tagged by the location (if any) whose country it
// falls in. Re-run after adding a country to src/lib/travel-data.ts:
//
//   node scripts/build-travel-dots.mjs

import { writeFile, readFile } from 'node:fs/promises'
import { geoContains, geoBounds } from 'd3-geo'
import { feature } from 'topojson-client'

// Frame: Atlantic edge of Ireland to the Gulf of Thailand
const BOUNDS = { west: -26, east: 112, north: 62, south: -2 }
const STEP = 1.25 // degrees between dots

const atlas = await fetch('https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json').then((r) => r.json())
const countries = feature(atlas, atlas.objects.countries).features.map((f) => ({ f, b: geoBounds(f) }))

// Location country names, in order, straight from the travel data source
const src = await readFile(new URL('../src/lib/travel-data.ts', import.meta.url), 'utf8')
const names = [...src.matchAll(/^\s{8}name: "(.+)",$/gm)].map((m) => m[1])

const inBox = ([lon, lat], [[w, s], [e, n]]) => lat >= s && lat <= n && (w <= e ? lon >= w && lon <= e : lon >= w || lon <= e)

const dots = []
const counts = new Array(names.length).fill(0)
for (let lat = BOUNDS.north; lat >= BOUNDS.south; lat -= STEP) {
    for (let lon = BOUNDS.west; lon <= BOUNDS.east; lon += STEP) {
        const p = [lon, lat]
        const hit = countries.find(({ f, b }) => inBox(p, b) && geoContains(f, p))
        if (!hit) continue
        const k = names.indexOf(hit.f.properties.name)
        if (k >= 0) counts[k]++
        dots.push([+(lon - BOUNDS.west).toFixed(2), +(BOUNDS.north - lat).toFixed(2), k])
    }
}

const missing = names.filter((n, i) => counts[i] === 0)
if (missing.length) console.warn(`No dots fell inside: ${missing.join(', ')} (their pins still show)`)

const out = `// Generated by scripts/build-travel-dots.mjs. Do not edit by hand.
// Each dot is [x, y, location index or -1], in degrees from the frame's top-left.

export const MAP_FRAME = ${JSON.stringify(BOUNDS)} as const

export const MAP_DOTS: [number, number, number][] = ${JSON.stringify(dots)}
`
await writeFile(new URL('../src/lib/travel-map-dots.ts', import.meta.url), out)
console.log(`${dots.length} dots; per location: ${names.map((n, i) => `${n} ${counts[i]}`).join(', ')}`)
